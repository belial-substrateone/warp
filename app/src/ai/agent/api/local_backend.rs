//! Local-LLM-backed agent replies for AnonWarp's stub-server mode.
//!
//! Translates a `warp_multi_agent_api::Request` into an OpenAI-style chat history, streams the
//! reply from the local LLM (see `crate::ai::local_llm`) and maps the text deltas onto the
//! protocol events the Warp server would have sent:
//!
//! 1. `StreamInit`
//! 2. on the first delta: `CreateTask` (new conversation) or `AddMessagesToTask` carrying an
//!    `AgentOutput` message
//! 3. every later delta: `AppendToMessageContent` with mask `agent_output.text`
//! 4. `StreamFinished` (`Done`, or `LLMUnavailable` after an error, in which case the error text
//!    is also shown as agent output so the user can see it).

use std::sync::Arc;

use anyhow::Result;
use api::response_event::stream_finished::{Done, InternalError, LlmUnavailable, Reason};
use futures::{Stream, StreamExt as _};
use warp_multi_agent_api as api;

use crate::ai::local_llm::{ChatMessage, LocalLlmConfig};
use crate::server::server_api::AIApiError;

const AGENT_OUTPUT_TEXT_PATH: &str = "agent_output.text";
/// Cap on characters of command output carried into the history, per tool result.
const MAX_TOOL_OUTPUT_CHARS: usize = 4000;

/// Agent reply events for `request`, generated by the configured local LLM.
pub fn local_agent_events(
    request: api::Request,
) -> impl Stream<Item = Result<api::ResponseEvent, Arc<AIApiError>>> + Send {
    let config = LocalLlmConfig::from_env();
    local_agent_events_with_config(request, config)
}

pub(super) fn local_agent_events_with_config(
    request: api::Request,
    config: LocalLlmConfig,
) -> impl Stream<Item = Result<api::ResponseEvent, Arc<AIApiError>>> + Send {
    let history = build_chat_history(&request);
    let meta = ReplyMeta::from_request(&request);
    let deltas = stream_chat(&config, &history);
    let base_url = config.base_url.clone();
    events_from_deltas(meta, base_url, deltas).map(Ok)
}

/// Streaming chat completion with owned inputs.
///
/// `local_llm::chat_completion_stream` is declared `impl Stream + 'static` but, under edition
/// 2024 capture rules, also captures its borrowed arguments, so it cannot be called with
/// non-`'static` references. This is the same request, built from owned data.
fn stream_chat(
    config: &LocalLlmConfig,
    messages: &[ChatMessage],
) -> impl Stream<Item = Result<String>> + Send + use<> {
    use anyhow::anyhow;
    static CLIENT: std::sync::OnceLock<http_client::Client> = std::sync::OnceLock::new();
    let client = CLIENT.get_or_init(http_client::Client::new_external);
    let body = serde_json::json!({
        "model": config.model,
        "messages": messages,
        "stream": true,
    });
    let mut builder = client
        .post(format!("{}/chat/completions", config.base_url))
        .json(&body);
    if let Some(key) = &config.api_key {
        builder = builder.bearer_auth(key);
    }
    builder.eventsource().filter_map(|event| async move {
        match event {
            Ok(reqwest_eventsource::Event::Open) => None,
            Ok(reqwest_eventsource::Event::Message(message)) => {
                if message.data.trim() == "[DONE]" {
                    return None;
                }
                match serde_json::from_str::<serde_json::Value>(&message.data) {
                    Ok(chunk) => chunk["choices"][0]["delta"]["content"]
                        .as_str()
                        .filter(|text| !text.is_empty())
                        .map(|text| Ok(text.to_owned())),
                    Err(err) => Some(Err(anyhow!("invalid local LLM stream chunk: {err}"))),
                }
            }
            Err(reqwest_eventsource::Error::StreamEnded) => None,
            Err(err) => Some(Err(anyhow!("local LLM stream failed: {err}"))),
        }
    })
}

/// Identifiers shared by all events of one reply.
#[derive(Clone, Debug)]
pub(super) struct ReplyMeta {
    conversation_id: String,
    request_id: String,
    task_id: String,
    has_root_task: bool,
}

impl ReplyMeta {
    pub(super) fn from_request(request: &api::Request) -> Self {
        let conversation_id = request
            .metadata
            .as_ref()
            .map(|m| m.conversation_id.clone())
            .filter(|id| !id.is_empty())
            .unwrap_or_else(|| uuid::Uuid::new_v4().to_string());
        // The root task is the one without a parent.
        let existing_root = request.task_context.as_ref().and_then(|ctx| {
            ctx.tasks.iter().find(|task| {
                task.dependencies
                    .as_ref()
                    .is_none_or(|deps| deps.parent_task_id.is_empty())
            })
        });
        Self {
            conversation_id,
            request_id: uuid::Uuid::new_v4().to_string(),
            has_root_task: existing_root.is_some(),
            task_id: existing_root
                .map(|task| task.id.clone())
                .unwrap_or_else(|| uuid::Uuid::new_v4().to_string()),
        }
    }
}

fn event(r#type: api::response_event::Type) -> api::ResponseEvent {
    api::ResponseEvent { r#type: Some(r#type) }
}

fn actions_event(action: api::client_action::Action) -> api::ResponseEvent {
    event(api::response_event::Type::ClientActions(
        api::response_event::ClientActions {
            actions: vec![api::ClientAction {
                action: Some(action),
            }],
        },
    ))
}

fn finished_event(reason: Reason) -> api::ResponseEvent {
    event(api::response_event::Type::Finished(
        api::response_event::StreamFinished {
            reason: Some(reason),
            ..Default::default()
        },
    ))
}

/// Turns streamed text into protocol events, tracking the open agent-output message.
struct Mapper {
    meta: ReplyMeta,
    open_message_id: Option<String>,
}

impl Mapper {
    fn text_event(&mut self, text: String) -> api::ResponseEvent {
        if let Some(message_id) = &self.open_message_id {
            return actions_event(api::client_action::Action::AppendToMessageContent(
                api::client_action::AppendToMessageContent {
                    task_id: self.meta.task_id.clone(),
                    message: Some(api::Message {
                        id: message_id.clone(),
                        task_id: self.meta.task_id.clone(),
                        request_id: self.meta.request_id.clone(),
                        message: Some(api::message::Message::AgentOutput(
                            api::message::AgentOutput { text },
                        )),
                        ..Default::default()
                    }),
                    mask: Some(prost_types::FieldMask {
                        paths: vec![AGENT_OUTPUT_TEXT_PATH.to_owned()],
                    }),
                },
            ));
        }
        let now = chrono::Utc::now();
        let message = api::Message {
            id: uuid::Uuid::new_v4().to_string(),
            task_id: self.meta.task_id.clone(),
            request_id: self.meta.request_id.clone(),
            timestamp: Some(prost_types::Timestamp {
                seconds: now.timestamp(),
                nanos: now.timestamp_subsec_nanos() as i32,
            }),
            message: Some(api::message::Message::AgentOutput(
                api::message::AgentOutput { text },
            )),
            ..Default::default()
        };
        self.open_message_id = Some(message.id.clone());
        let task_id = self.meta.task_id.clone();
        actions_event(if self.meta.has_root_task {
            api::client_action::Action::AddMessagesToTask(api::client_action::AddMessagesToTask {
                task_id,
                messages: vec![message],
            })
        } else {
            // After this the task exists; later messages go into it.
            self.meta.has_root_task = true;
            api::client_action::Action::CreateTask(api::client_action::CreateTask {
                task: Some(api::Task {
                    id: task_id,
                    messages: vec![message],
                    ..Default::default()
                }),
            })
        })
    }
}

/// Maps a stream of text deltas (or the error that ended it) to the full event sequence.
pub(super) fn events_from_deltas(
    meta: ReplyMeta,
    base_url: String,
    deltas: impl Stream<Item = Result<String>> + Send,
) -> impl Stream<Item = api::ResponseEvent> + Send {
    let init = event(api::response_event::Type::Init(
        api::response_event::StreamInit {
            conversation_id: meta.conversation_id.clone(),
            request_id: meta.request_id.clone(),
            run_id: uuid::Uuid::new_v4().to_string(),
        },
    ));
    let mut mapper = Mapper {
        meta,
        open_message_id: None,
    };
    let mut done = false;
    let body = deltas
        .map(Some)
        // `None` marks the end of the delta stream.
        .chain(futures::stream::once(async { None }))
        .filter_map(move |item| {
            let out: Option<Vec<api::ResponseEvent>> = if done {
                None
            } else {
                match item {
                    Some(Ok(text)) => Some(vec![mapper.text_event(text)]),
                    Some(Err(error)) => {
                        done = true;
                        let message = format!(
                            "Could not reach the local LLM at {base_url}: {error:#}. \
                             Set ANONWARP_LLM_BASE_URL / ANONWARP_LLM_MODEL."
                        );
                        let text = if mapper.open_message_id.is_some() {
                            format!("\n\n{message}")
                        } else {
                            message
                        };
                        Some(vec![
                            mapper.text_event(text),
                            finished_event(Reason::LlmUnavailable(LlmUnavailable::default())),
                        ])
                    }
                    None => {
                        done = true;
                        let mut events = Vec::new();
                        if mapper.open_message_id.is_none() {
                            events.push(
                                mapper.text_event("(The model returned no output.)".to_owned()),
                            );
                        }
                        events.push(finished_event(Reason::Done(Done::default())));
                        Some(events)
                    }
                }
            };
            futures::future::ready(out)
        })
        .flat_map(futures::stream::iter);
    futures::stream::once(async { init }).chain(body)
}

