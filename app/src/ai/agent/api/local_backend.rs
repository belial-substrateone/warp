/// Builds the chat messages (system prompt, prior turns, new input) for `request`.
pub(super) fn build_chat_history(request: &api::Request) -> Vec<ChatMessage> {
    let mut turns: Vec<(&'static str, String)> = Vec::new();
    if let Some(ctx) = &request.task_context {
        for task in &ctx.tasks {
            for message in &task.messages {
                if let Some((role, text)) = message_to_turn(message) {
                    turns.push((role, text));
                }
            }
        }
    }
    if let Some(input) = &request.input {
        for text in input_texts(input) {
            turns.push(("user", text));
        }
    }

    let mut messages = vec![ChatMessage::system(system_prompt(request.input.as_ref()))];
    // Merge consecutive same-role turns; many local chat templates require alternation.
    for (role, text) in turns {
        match messages.last_mut() {
            Some(last) if last.role == role => {
                last.content.push_str("\n\n");
                last.content.push_str(&text);
            }
            _ => messages.push(ChatMessage::new(role, text)),
        }
    }
    if messages.last().is_none_or(|m| m.role != "user") {
        messages.push(ChatMessage::user("Continue."));
    }
    messages
}

fn truncate(text: &str) -> String {
    if text.chars().count() <= MAX_TOOL_OUTPUT_CHARS {
        return text.to_owned();
    }
    let kept: String = text.chars().take(MAX_TOOL_OUTPUT_CHARS).collect();
    format!("{kept}\n[output truncated]")
}

fn message_to_turn(message: &api::Message) -> Option<(&'static str, String)> {
    use api::message::Message as M;
    match message.message.as_ref()? {
        M::UserQuery(q) if !q.query.is_empty() => Some(("user", q.query.clone())),
        M::AgentOutput(o) if !o.text.is_empty() => Some(("assistant", o.text.clone())),
        M::ToolCall(call) => {
            use api::message::tool_call::Tool;
            let text = match call.tool.as_ref()? {
                Tool::RunShellCommand(c) => format!("[Ran command: {}]", c.command),
                _ => "[Used a tool]".to_owned(),
            };
            Some(("assistant", text))
        }
        M::ToolCallResult(result) => {
            use api::message::tool_call_result::Result as R;
            let text = match result.result.as_ref()? {
                R::RunShellCommand(r) => {
                    use api::run_shell_command_result::Result as S;
                    match r.result.as_ref() {
                        Some(S::CommandFinished(f)) => format!(
                            "[Command `{}` finished with exit code {}. Output:\n{}]",
                            r.command,
                            f.exit_code,
                            truncate(&f.output)
                        ),
                        _ => format!("[Command `{}` did not complete]", r.command),
                    }
                }
                _ => "[Tool result]".to_owned(),
            };
            Some(("user", text))
        }
        _ => None,
    }
}

fn user_query_text(query: &api::request::input::UserQuery) -> Option<String> {
    (!query.query.is_empty()).then(|| query.query.clone())
}

/// Text turns for the new input; empty when there is nothing sensible to say (resume etc.).
fn input_texts(input: &api::request::Input) -> Vec<String> {
    use api::request::input::Type;
    let Some(kind) = &input.r#type else {
        return Vec::new();
    };
    match kind {
        Type::UserInputs(inputs) => inputs
            .inputs
            .iter()
            .filter_map(|i| {
                use api::request::input::user_inputs::user_input::Input as I;
                match i.input.as_ref()? {
                    I::UserQuery(q) => user_query_text(q),
                    I::CliAgentUserQuery(q) => q.user_query.as_ref().and_then(user_query_text),
                    I::ToolCallResult(r) => message_to_turn(&api::Message {
                        message: Some(api::message::Message::ToolCallResult(
                            api::message::ToolCallResult {
                                tool_call_id: r.tool_call_id.clone(),
                                result: r.result.clone().and_then(convert_result),
                                ..Default::default()
                            },
                        )),
                        ..Default::default()
                    })
                    .map(|(_, text)| text),
                    _ => None,
                }
            })
            .collect(),
        #[allow(deprecated)]
        Type::UserQuery(q) => user_query_text(q).into_iter().collect(),
        Type::QueryWithCannedResponse(q) => {
            (!q.query.is_empty()).then(|| q.query.clone()).into_iter().collect()
        }
        Type::AutoCodeDiffQuery(q) => {
            (!q.query.is_empty()).then(|| q.query.clone()).into_iter().collect()
        }
        // ResumeConversation and everything else: the caller appends "Continue.".
        _ => Vec::new(),
    }
}

/// The request-side and message-side tool results are different types; convert the one
/// variant we render (shell commands) and drop the rest.
fn convert_result(
    result: api::request::input::tool_call_result::Result,
) -> Option<api::message::tool_call_result::Result> {
    use api::request::input::tool_call_result::Result as In;
    match result {
        In::RunShellCommand(r) => Some(api::message::tool_call_result::Result::RunShellCommand(r)),
        _ => None,
    }
}

fn system_prompt(input: Option<&api::request::Input>) -> String {
    let mut prompt = String::from(
        "You are a concise assistant embedded in a terminal. Help the user with shell \
         commands, scripts, code, and system questions. Put commands and code in fenced \
         code blocks. You cannot run commands yourself; suggest them for the user to run.",
    );
    if let Some(ctx) = input.and_then(|i| i.context.as_ref()) {
        if let Some(dir) = ctx.directory.as_ref().filter(|d| !d.pwd.is_empty()) {
            prompt.push_str(&format!("\nCurrent directory: {}", dir.pwd));
        }
        if let Some(shell) = ctx.shell.as_ref().filter(|s| !s.name.is_empty()) {
            prompt.push_str(&format!("\nShell: {}", shell.name));
        }
        if let Some(os) = ctx.operating_system.as_ref().filter(|o| !o.platform.is_empty()) {
            prompt.push_str(&format!("\nOS: {}", os.platform));
            if !os.distribution.is_empty() {
                prompt.push_str(&format!(" ({})", os.distribution));
            }
        }
    }
    prompt
}

/// Event for a reply that failed before any streaming started (kept for callers that want a
/// one-shot error); unused internally but handy for `InternalError`.
#[allow(dead_code)]
pub(super) fn internal_error_event(message: String) -> api::ResponseEvent {
    finished_event(Reason::InternalError(InternalError { message }))
}

